import test from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';

const read = relative => readFileSync(new URL(`../../${relative}`, import.meta.url), 'utf8');
const has = (text, phrases) => {
  for (const phrase of phrases) assert.ok(text.includes(phrase), `Missing course contract: ${phrase}`);
};

test('all setup routes link official skills and require agent instruction reads', () => {
  for (const runtime of ['nodejs', 'java']) {
    has(read(`course/lessons/00-environment-setup.${runtime}.md`), ['course/docs/CAP-SKILLS.md', 'cap-developer SKILL.md', 'activation pending']);
  }
  has(read('course/docs/SHORT-STARTER.md'), ['CAP-SKILLS.md', 'active cap-developer instruction reads', 'install-starter.mjs', 'do not overwrite it']);
  has(read('course/docs/CAP-SKILLS.md'), ['never regenerated by a skill', 'Installation is not activation', 'current task', 'capDeveloperActivation: pending|confirmed']);
});

test('final browser lesson stays free exploration with learner-reported comparison', () => {
  const final = read('course/docs/FINAL-AGENT-ACTIVITY.md');
  has(final, ['optional examples', 'not three required activities', 'Do not require every example, a follow-up', 'learner-reported verification']);
  has(read('course/BUILDER.md'), ['course/docs/FINAL-AGENT-ACTIVITY.md', 'free browser exploration', 'no required follow-up', 'setup/runtime details only']);
});

test('official CAP evidence fallback does not clear native or application MCP checks', () => {
  const policy = read('course/docs/CAP-SKILLS.md');
  has(policy, ['https://cap.cloud.sap/docs/llms.txt', 'cds compile', 'failed native CAP MCP setup remains pending', 'does not complete application MCP, Fiori generation or UI5 requirements']);
  const recovery = read('course/docs/EXTENSION-TROUBLESHOOTING.md');
  has(recovery, ['first diagnose/recover', 'CAP-SKILLS.md', 'native CAP MCP setup pending', 'Application MCP runtime, Fiori and UI5 checks still require their actual tools and results']);
});

test('skill installation and refresh remain explicit project operations', () => {
  const policy = read('course/docs/CAP-SKILLS.md');
  has(policy, ['does not inspect installation state', '--verify', 'not an update command', '--skill cap-developer cap-add-remote-service cap-trivia cap-upgrade --agent codex --copy', 'no `-g`', 'back up existing local modifications', 'not a required install pin']);
  has(policy, ['Node.js recipes must not be applied to a Java application', 'never automatically invoked', 'prepared CommonJS starter']);
});
